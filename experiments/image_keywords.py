def normalize(text):
    text = SIMPLIFY.convert(text).replace("祢", "你").replace("祂", "他")
    return re.sub(r"\s+", " ", text).strip()


def read_song(title, album):
    SOURCES.mkdir(parents=True, exist_ok=True)
    source = f"https://sop.org/music/{album}/"
    cached = SOURCES / (album + ".html")
    if not cached.exists():
        response = requests.get(source, timeout=45)
        response.raise_for_status()
        cached.write_bytes(response.content)
    soup = BeautifulSoup(cached.read_text(encoding="utf-8"), "html.parser")
    heading = soup.find(lambda tag: tag.name == "h5" and tag.get_text(strip=True) == title)
    if heading is None:
        raise RuntimeError(f"Missing song heading: {title}")
    blocks = heading.parent.find_all("p", recursive=False)
    lyrics = "\n".join(block.get_text("\n", strip=True) for block in blocks)
    if len(lyrics) < 40:
        raise RuntimeError(f"Insufficient lyrics: {title}")
    lines = list(dict.fromkeys(normalize(line) for line in lyrics.splitlines() if normalize(line)))
    return {"title": title, "source": source, "lyrics": lyrics, "lines": lines}


def unit(vector):
    return vector / max(float(np.linalg.norm(vector)), 1e-12)


class Encoder:
    def __init__(self):
        self.tokenizer = Tokenizer.from_file(str(MODEL / "tokenizer.json"))
        self.tokenizer.enable_truncation(max_length=128)
        self.tokenizer.enable_padding(pad_id=1, pad_token="<pad>")
        options = ort.SessionOptions()
        options.intra_op_num_threads = 4
        options.inter_op_num_threads = 1
        self.session = ort.InferenceSession(str(MODEL / "onnx/model_quint8_avx2.onnx"),
            sess_options=options, providers=["CPUExecutionProvider"])
        self.input_names = {v.name for v in self.session.get_inputs()}
        self.cache = {}

    def encode(self, texts):
        missing = list(dict.fromkeys(text for text in texts if text not in self.cache))
        for start in range(0, len(missing), 12):
            batch = missing[start:start + 12]
            tokens = self.tokenizer.encode_batch(batch)
            inputs = {"input_ids": np.array([t.ids for t in tokens], dtype=np.int64),
                      "attention_mask": np.array([t.attention_mask for t in tokens], dtype=np.int64),
                      "token_type_ids": np.array([t.type_ids for t in tokens], dtype=np.int64)}
            outputs = self.session.run(None, {k: v for k, v in inputs.items() if k in self.input_names})
            hidden = outputs[0]
            mask = inputs["attention_mask"][..., None]
            pooled = (hidden * mask).sum(axis=1) / mask.sum(axis=1).clip(min=1)
            for text, vector in zip(batch, pooled):
                self.cache[text] = unit(vector)
        return np.stack([self.cache[t] for t in texts])

    def chunks(self, lines):
        chunks, pending = [], ""
        for line in lines:
            joined = (pending + " " + line).strip()
            # This experiment's source lines fit individually into 126 tokens.
            token_count = len(self.tokenizer.encode(joined, add_special_tokens=False).ids)
            if token_count > 110 and pending:
                chunks.append(pending)
                pending = line
            else:
                pending = joined
        if pending:
            chunks.append(pending)
        return chunks


def candidates(song):
    words = list(jieba.posseg.cut(normalize(song["title"] + " " + song["lyrics"])))
    counts = Counter(word for word, pos in words if 2 <= len(word) <= 6 and
        re.fullmatch(r"[\u3400-\u9fff]+", word) and pos[0] in "nva" and word not in STOP)
    return list(counts)


def diverse_top(scores, vectors, count=3, weight=.8):
    remaining = list(range(len(scores)))
    chosen = []
    while remaining and len(chosen) < count:
        def score(i):
            redundancy = max((float(vectors[i] @ vectors[j]) for j in chosen), default=0)
            return weight * float(scores[i]) - (1 - weight) * redundancy
        best = max(remaining, key=score)
        chosen.append(best)
        remaining.remove(best)
    return chosen


def search_link(query):
    return "https://www.google.com/search?" + urlencode({"udm": "2", "q": query,
        "tbs": "iar:w,ift:png,isz:lt,islt:2mp"})


def main():
    started = time.perf_counter()
    jieba.setLogLevel(logging.ERROR)
    encoder = Encoder()
    scene_vectors = encoder.encode([s[2] for s in SCENES])
    reports = []
    for title, album in SONGS:
        timer = time.perf_counter()
        song = read_song(title, album)
        chunks = encoder.chunks(song["lines"])
        chunk_vectors = encoder.encode(chunks)
        lyric_vector = unit(chunk_vectors.mean(axis=0))
        title_vector = encoder.encode([normalize(title)])[0]
        document = unit(.85 * lyric_vector + .15 * title_vector)
        phrases = candidates(song)
        phrase_vectors = encoder.encode(phrases)
        phrase_scores = phrase_vectors @ document
        raw = diverse_top(phrase_scores, phrase_vectors)
        raw_terms = [{"term": TRADITIONAL.convert(phrases[i]), "cosine": round(float(phrase_scores[i]), 4)} for i in raw]
        # The same visual-scene vocabulary and weights apply to every song.
        semantic = .7 * (scene_vectors @ document) + .3 * (scene_vectors @ chunk_vectors.T).max(axis=1)
        normalized = normalize(song["title"] + " " + song["lyrics"])
        hits = [[cue for cue in scene[4].split() if cue in normalized] for scene in SCENES]
        # Literal visual imagery should not disappear behind generic religious themes.
        title_text = normalize(song["title"])
        title_bonus = np.array([.35 if any(cue in title_text for cue in scene[4].split()) else 0 for scene in SCENES])
        bonus = np.array([min(len(cues), 2) * .18 for cues in hits]) + title_bonus
        hybrid = semantic + bonus
        ranked = diverse_top(hybrid, scene_vectors, weight=.85)
        suggestions = [{"scene": SCENES[i][0], "keywords": SCENES[i][1], "query": SCENES[i][3],
            "model_score": round(float(semantic[i]), 4), "literal_bonus": round(float(bonus[i]), 4),
            "title_match": bool(title_bonus[i]), "visual_cue_count": len(hits[i]),
            "search_link": search_link(SCENES[i][3])} for i in ranked]
        baseline = np.argsort(-semantic)[:3]
        # Verify both scripts on equivalent text; this is stability, not accuracy.
        traditional_chunks = encoder.chunks([TRADITIONAL.convert(line) for line in song["lines"]])
        traditional = unit(encoder.encode(traditional_chunks).mean(axis=0))
        report = {"title": title, "source": song["source"], "lyric_characters": len(song["lyrics"]),
            "lyric_sha256": hashlib.sha256(song["lyrics"].encode()).hexdigest(), "unique_lines": len(song["lines"]),
            "chunks": len(chunks), "candidate_count": len(phrases), "raw_keywords": raw_terms,
            "simplified_normalizes_identically": normalize(song["lyrics"]) == normalize(SIMPLIFY.convert(song["lyrics"])),
            "semantic_only_scenes": [SCENES[i][1] for i in baseline], "suggestions": suggestions,
            "traditional_simplified_cosine": round(float(lyric_vector @ traditional), 4),
            "seconds": round(time.perf_counter() - timer, 3)}
        reports.append(report)
        print(json.dumps(report, ensure_ascii=False), flush=True)
    OUTPUT.mkdir(parents=True, exist_ok=True)
    result = {"model": "paraphrase-multilingual-MiniLM-L12-v2, UINT8 AVX2 ONNX", "providers": encoder.session.get_providers(),
        "dimensions": 384, "max_tokens": 128, "normalization": "Traditional/Simplified -> Simplified; pronoun normalization",
        "title_weight": .15, "lyric_weight": .85, "scene_candidates": len(SCENES),
        "seconds_total": round(time.perf_counter() - started, 3), "songs": reports}
    (OUTPUT / "results.json").write_text(json.dumps(result, ensure_ascii=False, indent=2), encoding="utf-8")
